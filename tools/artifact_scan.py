"""Artifact detection phase: sweep every shipped scene for editing artifacts.

Reads scan jobs from tools/audit_out/scan_plan.json (generated by
tools/artifact_review/make_scan_plan.ts). Overlapping tiles of every scene
image go through an inverted artifact-hunt question ("answer YES if you see
ANY editing mistake"), threaded for speed. Flags are saved as crops for human
review.

Input: tools/audit_out/scan_plan.json
Output: tools/audit_out/artifact_scan/artifact_report.json + flagged crop PNGs.
"""

from __future__ import annotations

import argparse
import json
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

ROOT = Path(__file__).resolve().parent.parent
SCAN_PLAN = ROOT / "tools" / "audit_out" / "scan_plan.json"
OUT = ROOT / "tools" / "audit_out" / "artifact_scan"

ARTIFACT_Q = (
    "You are inspecting one region of a children's book illustration for "
    "EDITING MISTAKES. Answer YES if you see ANY of: a pale or white "
    "rectangular patch, an erased-looking smear, a blurry spot unlike the "
    "rest, a half-drawn or cut-off object, a hard rectangular seam, or a "
    "style clash. Answer NO if the region looks cleanly illustrated."
)


def tiles(w: int, h: int, cols: int = 3, rows: int = 2, overlap: float = 0.25):
    tw, th = w // cols, h // rows
    ox, oy = int(tw * overlap), int(th * overlap)
    for r in range(rows):
        for c in range(cols):
            x0 = max(0, c * tw - ox)
            y0 = max(0, r * th - oy)
            x1 = min(w, (c + 1) * tw + ox)
            y1 = min(h, (r + 1) * th + oy)
            yield (x0, y0, x1, y1)


def judge_tile(job: dict) -> dict | None:
    from PIL import Image
    from gen.judge import ask_yes_no

    path = job["asset"]["path"]
    rect = job["rect"]
    tag = job["tag"]
    img_path = Path(path)
    if not img_path.is_absolute():
        img_path = ROOT / img_path
    with Image.open(img_path) as im:
        crop = im.convert("RGB").crop(rect)
    if ask_yes_no(ARTIFACT_Q, [crop]):
        OUT.mkdir(parents=True, exist_ok=True)
        crop_name = f"{tag}.png"
        crop.save(OUT / crop_name)
        return {"asset": path, "kind": "judged-artifact",
                "rect": list(rect), "crop": crop_name}
    return None


def main(argv: list[str] | None = None) -> None:
    global OUT

    parser = argparse.ArgumentParser(
        description="Sweep shipped scenes for editing artifacts."
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=OUT,
        metavar="DIR",
        help="output directory (default: %(default)s)",
    )
    args = parser.parse_args(argv)
    OUT = args.out

    if not SCAN_PLAN.exists():
        raise SystemExit(
            f"{SCAN_PLAN} not found; run tools/artifact_review/make_scan_plan.ts first"
        )

    batches = json.loads(SCAN_PLAN.read_text())
    jobs = [job for batch in batches for job in batch]
    findings: list[dict] = []

    print(f"judging {len(jobs)} tiles...")
    with ThreadPoolExecutor(max_workers=8) as pool:
        for res in pool.map(judge_tile, jobs):
            if res:
                findings.append(res)
                print(f"  FLAG {res['asset']} tile {res.get('rect')}")

    OUT.mkdir(parents=True, exist_ok=True)
    report_path = OUT / "artifact_report.json"
    report_path.write_text(json.dumps(findings, indent=2))
    try:
        report_display = report_path.resolve().relative_to(ROOT.resolve())
    except ValueError:
        report_display = report_path
    print(f"\n{len(findings)} findings -> {report_display}")


if __name__ == "__main__":
    main()
